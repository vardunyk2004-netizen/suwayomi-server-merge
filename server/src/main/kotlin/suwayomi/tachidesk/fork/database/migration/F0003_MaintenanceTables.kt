package suwayomi.tachidesk.fork.database.migration

import org.jetbrains.exposed.v1.jdbc.JdbcTransaction
import suwayomi.tachidesk.fork.database.ForkMigration
import suwayomi.tachidesk.graphql.types.DatabaseType
import suwayomi.tachidesk.server.serverConfig

/** Tables for duplicate detection (F10) and persisted maintenance reports (F11 reindex, F12 doctor). */
@Suppress("ClassName")
class F0003_MaintenanceTables : ForkMigration {
    override val version = 3
    override val name = "MaintenanceTables"

    override fun apply(transaction: JdbcTransaction) {
        statements().forEach { statement -> transaction.exec(statement) }
    }

    private fun statements(): List<String> {
        val text = if (serverConfig.databaseType.value == DatabaseType.POSTGRESQL) "TEXT" else "VARCHAR"
        return listOf(
            """
            CREATE TABLE IF NOT EXISTS fork_duplicate_signature (
                manga_id INT PRIMARY KEY,
                algorithm_version INT NOT NULL,
                normalized_title VARCHAR(512) NOT NULL,
                core_title VARCHAR(512) NOT NULL,
                tokens $text NOT NULL,
                sequel_marker VARCHAR(64),
                computed_at BIGINT NOT NULL,
                CONSTRAINT fk_fork_duplicate_signature_manga FOREIGN KEY (manga_id) REFERENCES manga(id) ON DELETE CASCADE
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_duplicate_signature_core ON fork_duplicate_signature(core_title)",
            """
            CREATE TABLE IF NOT EXISTS fork_duplicate_ignored_pair (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                manga_id_low INT NOT NULL,
                manga_id_high INT NOT NULL,
                created_at BIGINT NOT NULL,
                CONSTRAINT uq_fork_duplicate_ignored_pair UNIQUE (manga_id_low, manga_id_high),
                CONSTRAINT fk_fork_duplicate_ignored_low FOREIGN KEY (manga_id_low) REFERENCES manga(id) ON DELETE CASCADE,
                CONSTRAINT fk_fork_duplicate_ignored_high FOREIGN KEY (manga_id_high) REFERENCES manga(id) ON DELETE CASCADE
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_duplicate_ignored_low ON fork_duplicate_ignored_pair(manga_id_low)",
            "CREATE INDEX IF NOT EXISTS idx_fork_duplicate_ignored_high ON fork_duplicate_ignored_pair(manga_id_high)",
            """
            CREATE TABLE IF NOT EXISTS fork_maintenance_report (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind VARCHAR(32) NOT NULL,
                dry_run BOOLEAN NOT NULL,
                payload $text NOT NULL,
                created_at BIGINT NOT NULL
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_maintenance_report_kind ON fork_maintenance_report(kind)",
        )
    }
}
