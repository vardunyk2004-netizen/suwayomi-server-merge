package suwayomi.tachidesk.fork.database.migration

import org.jetbrains.exposed.v1.jdbc.JdbcTransaction
import suwayomi.tachidesk.fork.database.ForkMigration
import suwayomi.tachidesk.graphql.types.DatabaseType
import suwayomi.tachidesk.server.serverConfig

/**
 * Additive details for merge links, parts, fallbacks and series-split views.
 *
 * Only fork tables are touched. Upstream tables/columns are never altered (decision 12 B).
 * `ADD COLUMN IF NOT EXISTS` / `CREATE ... IF NOT EXISTS` keep a re-run harmless; the runner
 * ledger normally prevents a second run anyway.
 *
 * F0001 declared the JSON payload/options columns as CLOB (H2) / JSONB (PostgreSQL). Exposed maps
 * fork JSON as plain unlimited text (like upstream `memo`, see `JsonObjectColumn.kt`), and a
 * text parameter cannot be bound to a JSONB column without a cast, so both columns are converted
 * to the upstream unlimited-text type here. The tables are empty until a fork feature is enabled.
 */
@Suppress("ClassName")
class F0002_MergeLinkDetails : ForkMigration {
    override val version = 2
    override val name = "MergeLinkDetails"

    override fun apply(transaction: JdbcTransaction) {
        statements().forEach { statement -> transaction.exec(statement) }
    }

    private fun statements(): List<String> {
        val isPostgres = serverConfig.databaseType.value == DatabaseType.POSTGRESQL
        val text = if (isPostgres) "TEXT" else "VARCHAR"
        // H2: SET DATA TYPE keeps NOT NULL/DEFAULT (a bare column definition would replace them).
        val alterType = if (isPostgres) "TYPE $text" else "SET DATA TYPE $text"

        return listOf(
            "ALTER TABLE fork_merge_journal ALTER COLUMN payload $alterType",
            "ALTER TABLE fork_merge_group ALTER COLUMN options $alterType",
            // Sequence offsets can be fractional (e.g. a sequel restarting at 0.5).
            if (isPostgres) {
                "ALTER TABLE fork_merge_source ALTER COLUMN chapter_offset TYPE REAL"
            } else {
                "ALTER TABLE fork_merge_source ALTER COLUMN chapter_offset SET DATA TYPE REAL"
            },
            "ALTER TABLE fork_merge_journal ADD COLUMN IF NOT EXISTS reversible BOOLEAN DEFAULT TRUE NOT NULL",
            "ALTER TABLE fork_merge_journal ADD COLUMN IF NOT EXISTS undone_at BIGINT",
            "ALTER TABLE fork_merge_journal ADD COLUMN IF NOT EXISTS error_message VARCHAR(2048)",
            // Real identity of the linked source chapter (D2, D25).
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS original_number REAL DEFAULT -1 NOT NULL",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS original_scanlator VARCHAR(256)",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS original_upload_date BIGINT DEFAULT 0 NOT NULL",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS entry_key VARCHAR(512) DEFAULT '' NOT NULL",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS link_kind VARCHAR(16) DEFAULT 'CHAPTER' NOT NULL",
            // Part ranges (F3) are 0-based inclusive page indexes of the source chapter.
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS page_start INT",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS page_end INT",
            "ALTER TABLE fork_chapter_link ADD COLUMN IF NOT EXISTS source_page_count_snapshot INT DEFAULT -1 NOT NULL",
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_link_status ON fork_chapter_link(status)",
            """
            CREATE TABLE IF NOT EXISTS fork_chapter_fallback (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                link_id INT NOT NULL,
                source_chapter_id INT,
                source_manga_id INT NOT NULL,
                rank INT NOT NULL,
                CONSTRAINT uq_fork_chapter_fallback_link_rank UNIQUE (link_id, rank),
                CONSTRAINT fk_fork_chapter_fallback_link FOREIGN KEY (link_id) REFERENCES fork_chapter_link(id) ON DELETE CASCADE,
                CONSTRAINT fk_fork_chapter_fallback_source FOREIGN KEY (source_chapter_id) REFERENCES chapter(id) ON DELETE SET NULL,
                CONSTRAINT fk_fork_chapter_fallback_source_manga FOREIGN KEY (source_manga_id) REFERENCES manga(id) ON DELETE RESTRICT
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_fallback_link ON fork_chapter_fallback(link_id)",
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_fallback_source ON fork_chapter_fallback(source_chapter_id)",
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_fallback_source_manga ON fork_chapter_fallback(source_manga_id)",
            // Chapter-level merge: one virtual chapter built from several page ranges (F3).
            """
            CREATE TABLE IF NOT EXISTS fork_chapter_part (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                merged_chapter_id INT NOT NULL,
                part_index INT NOT NULL,
                source_chapter_id INT,
                source_manga_id INT NOT NULL,
                page_start INT NOT NULL,
                page_end INT NOT NULL,
                source_page_count_snapshot INT NOT NULL,
                status VARCHAR(32) NOT NULL,
                CONSTRAINT uq_fork_chapter_part_index UNIQUE (merged_chapter_id, part_index),
                CONSTRAINT fk_fork_chapter_part_merged FOREIGN KEY (merged_chapter_id) REFERENCES chapter(id) ON DELETE CASCADE,
                CONSTRAINT fk_fork_chapter_part_source FOREIGN KEY (source_chapter_id) REFERENCES chapter(id) ON DELETE SET NULL,
                CONSTRAINT fk_fork_chapter_part_source_manga FOREIGN KEY (source_manga_id) REFERENCES manga(id) ON DELETE RESTRICT
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_part_merged ON fork_chapter_part(merged_chapter_id)",
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_part_source ON fork_chapter_part(source_chapter_id)",
            "CREATE INDEX IF NOT EXISTS idx_fork_chapter_part_source_manga ON fork_chapter_part(source_manga_id)",
            // Series split (F4): a view over a subset of ONE manga's chapters. A manga may back several
            // split views, so membership is not stored in fork_merge_source (unique per manga, D10).
            """
            CREATE TABLE IF NOT EXISTS fork_split_source (
                id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                group_id INT NOT NULL,
                source_manga_id INT NOT NULL,
                CONSTRAINT uq_fork_split_source_group UNIQUE (group_id),
                CONSTRAINT fk_fork_split_source_group FOREIGN KEY (group_id) REFERENCES fork_merge_group(id) ON DELETE CASCADE,
                CONSTRAINT fk_fork_split_source_manga FOREIGN KEY (source_manga_id) REFERENCES manga(id) ON DELETE RESTRICT
            )
            """.trimIndent(),
            "CREATE INDEX IF NOT EXISTS idx_fork_split_source_group ON fork_split_source(group_id)",
            "CREATE INDEX IF NOT EXISTS idx_fork_split_source_manga ON fork_split_source(source_manga_id)",
        )
    }
}
